static uint32_t rgb_to_abgr(uint32_t rgb) {
    uint32_t r = (rgb >> 16) & 0xFFU;
    uint32_t g = (rgb >> 8)  & 0xFFU;
    uint32_t b =  rgb        & 0xFFU;
    return 0xFF000000U | (b << 16) | (g << 8) | r;
}

static void scroll_up_one_line(void) {
    if (!s_fb) {
        return;
    }

    int copy_rows = SCREEN_HEIGHT - LINE_H;
    memmove(s_fb, s_fb + (LINE_H * SCREEN_PITCH), (size_t)copy_rows * SCREEN_PITCH * sizeof(uint32_t));

    uint32_t *bottom = s_fb + (copy_rows * SCREEN_PITCH);
    for (int i = 0; i < LINE_H * SCREEN_PITCH; i++) {
        bottom[i] = s_bg_color;
    }

    s_cursor_y -= LINE_H;
    if (s_cursor_y < MARGIN_Y) {
        s_cursor_y = MARGIN_Y;
    }
}

static void draw_glyph(int x, int y, char ch) {
    if (!s_fb) {
        return;
    }

    unsigned char uc = (unsigned char)ch;
    if (uc < 0x20 || uc > 0x7E) {
        uc = '?';
    }

    const uint8_t *glyph = s_font8x8[uc - 0x20];
    for (int row = 0; row < GLYPH_H; row++) {
        int py = y + row;
        if (py < 0 || py >= SCREEN_HEIGHT) {
            continue;
        }
        uint32_t *dst_row = s_fb + (py * SCREEN_PITCH);
        uint8_t bits = glyph[row];
        for (int col = 0; col < GLYPH_W; col++) {
            int px = x + col;
            if (px < 0 || px >= SCREEN_WIDTH) {
                continue;
            }
            dst_row[px] = (bits & (0x80U >> col)) ? s_fg_color : s_bg_color;
        }
    }
}

static void clear_current_line(void) {
    if (!s_fb) {
        return;
    }

    for (int row = 0; row < LINE_H; row++) {
        int py = s_cursor_y + row;
        if (py < 0 || py >= SCREEN_HEIGHT) {
            continue;
        }
        uint32_t *dst_row = s_fb + (py * SCREEN_PITCH);
        for (int px = MARGIN_X; px < SCREEN_WIDTH - MARGIN_X; px++) {
            dst_row[px] = s_bg_color;
        }
    }
}

static void put_char(char ch) {
    if (ch == '\r') {
        s_cursor_x = MARGIN_X;
        clear_current_line();
        return;
    }

    if (ch == '\n') {
        s_cursor_x = MARGIN_X;
        s_cursor_y += LINE_H;
        if (s_cursor_y + GLYPH_H >= SCREEN_HEIGHT - MARGIN_Y) {
            scroll_up_one_line();
        }
        return;
    }

    if (ch == '\t') {
        int tab_w = GLYPH_W * 4;
        s_cursor_x = ((s_cursor_x - MARGIN_X + tab_w) / tab_w) * tab_w + MARGIN_X;
        if (s_cursor_x + GLYPH_W >= SCREEN_WIDTH - MARGIN_X) {
            put_char('\n');
        }
        return;
    }

    if (s_cursor_x + GLYPH_W >= SCREEN_WIDTH - MARGIN_X) {
        put_char('\n');
    }

    draw_glyph(s_cursor_x, s_cursor_y, ch);
    s_cursor_x += GLYPH_W;
}

int psvDebugScreenInit(void) {
    if (s_fb) {
        return 0;
    }

    s_fb_uid = sceKernelAllocMemBlock("safe_itls_fb",
                                      SCE_KERNEL_MEMBLOCK_TYPE_USER_CDRAM_RW,
                                      FB_MEM_SIZE,
                                      NULL);
    if (s_fb_uid < 0) {
        return s_fb_uid;
    }

    void *base = NULL;
    int res = sceKernelGetMemBlockBase(s_fb_uid, &base);
    if (res < 0 || !base) {
        sceKernelFreeMemBlock(s_fb_uid);
        s_fb_uid = -1;
        return (res < 0) ? res : -1;
    }

    s_fb = (uint32_t *)base;
    psvDebugScreenClear(0x000000);

    SceDisplayFrameBuf fb;
    memset(&fb, 0, sizeof(fb));
    fb.size        = sizeof(SceDisplayFrameBuf);
    fb.base        = s_fb;
    fb.pitch       = SCREEN_PITCH;
    fb.pixelformat = SCE_DISPLAY_PIXELFORMAT_A8B8G8R8;
    fb.width       = SCREEN_WIDTH;
    fb.height      = SCREEN_HEIGHT;

    sceDisplaySetFrameBuf(&fb, SCE_DISPLAY_SETBUF_NEXTFRAME);
    return 0;
}

void psvDebugScreenClear(uint32_t color) {
    s_bg_color = rgb_to_abgr(color);
    s_cursor_x = MARGIN_X;
    s_cursor_y = MARGIN_Y;

    if (!s_fb) {
        return;
    }

    size_t total_pixels = (size_t)SCREEN_PITCH * SCREEN_HEIGHT;
    for (size_t i = 0; i < total_pixels; i++) {
        s_fb[i] = s_bg_color;
    }
}

int psvDebugScreenPrintf(const char *format, ...) {
    if (!format) {
        return 0;
    }

    char buf[1024];
    va_list args;
    va_start(args, format);
    int len = vsnprintf(buf, sizeof(buf), format, args);
    va_end(args);

    if (len <= 0) {
        return len;
    }

    for (int i = 0; buf[i] != '\0'; i++) {
        put_char(buf[i]);
    }

    return len;
}

void psvDebugScreenTerm(void) {
    if (s_fb_uid >= 0) {
        sceKernelFreeMemBlock(s_fb_uid);
        s_fb_uid = -1;
    }
    s_fb = NULL;
}
